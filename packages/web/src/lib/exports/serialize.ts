/**
 * Pure serializers for the 3 `/exports/*` payloads.
 *
 * Spec docs/spec/cloud-resource-manager.md §6.7, §6.7.1, §7.5.
 *
 * No I/O. Every function returns a JSON-compatible object the route
 * handler wraps into a `NextResponse.json(...)`. The cleartext side
 * (unseal, assemble `.env` lines) lives in the browser.
 */

import type { ScopedResourceRow } from '@/lib/mcp/resolve-scope';
import type { SealedAccessRow, SecretManagerLookup } from '@/lib/exports/resolve';
import type { ComposedMcpConfig } from '@crm/core/mcp';

/**
 * Body returned by `POST /exports/env`. Each entry pairs an access
 * `key` with its sealed_blob — the browser unseal as much as it can
 * (recipient-gated) and assembles the `.env` (or `.env.json`) locally.
 *
 * `source_resource_id` lets the browser surface "the value for X comes
 * from Resource Y" in the UI when a placeholder cannot be resolved.
 */
export interface ExportEnvBody {
  readonly format: 'dotenv' | 'json';
  readonly entries: ReadonlyArray<{
    readonly key: string;
    readonly source_resource_id: string;
    readonly source_resource_name: string;
    readonly source_kind: string;
    readonly sealed_blob: unknown;
    readonly recipient_fingerprints: ReadonlyArray<string>;
  }>;
}

export function serializeExportEnv(
  format: 'dotenv' | 'json',
  resources: ReadonlyArray<ScopedResourceRow>,
  accesses: ReadonlyArray<SealedAccessRow>,
): ExportEnvBody {
  const resByResource = new Map<string, ScopedResourceRow>();
  for (const r of resources) resByResource.set(r.id, r);
  const entries = accesses
    .map((a) => {
      const r = resByResource.get(a.resource_id);
      // RLS could theoretically hand us an orphan access row in
      // edge-cases (membership flap). Skip; the resource is the
      // anchor.
      if (!r) return null;
      return {
        key: a.key,
        source_resource_id: a.resource_id,
        source_resource_name: r.name,
        source_kind: r.kind,
        sealed_blob: a.sealed_blob,
        recipient_fingerprints: a.recipient_fingerprints,
      };
    })
    .filter((e): e is NonNullable<typeof e> => e !== null);
  return { format, entries };
}

/**
 * Body returned by `POST /exports/mcp`. Pairs the `mcp_json` snapshot
 * (composed via `composeMcpConfig`) with the env companion. The browser
 * uses `mcp_json` as-is, and unseals each manifest entry to produce
 * the `.env-mcp` companion file with concrete values where possible.
 *
 * `env_dotenv_template` is a pre-rendered `.env` skeleton with the
 * placeholders left as `${KEY}` lines — handy for showing the
 * user what the file *would* look like before unseal, and serving
 * as the cleartext-free preview in the UI.
 */
export interface ExportMcpBody {
  readonly mcp_json: ComposedMcpConfig['mcpJson'];
  readonly env_manifest: ComposedMcpConfig['envManifest'];
  readonly env_dotenv_template: string;
  readonly env_entries: ReadonlyArray<{
    readonly key: string;
    readonly source_resource_id: string;
    readonly source_resource_name: string;
    readonly source_kind: string;
    readonly sealed_blob: unknown;
    readonly recipient_fingerprints: ReadonlyArray<string>;
  }>;
}

export function serializeExportMcp(
  composed: ComposedMcpConfig,
  resources: ReadonlyArray<ScopedResourceRow>,
  accesses: ReadonlyArray<SealedAccessRow>,
): ExportMcpBody {
  const resByResource = new Map<string, ScopedResourceRow>();
  for (const r of resources) resByResource.set(r.id, r);

  // Index accesses by (resource_id, key) so we can join with the
  // manifest output.
  const accessByPair = new Map<string, SealedAccessRow>();
  for (const a of accesses) accessByPair.set(`${a.resource_id}:${a.key}`, a);

  const envEntries = composed.envManifest.keys.map((m) => {
    const r = resByResource.get(m.source_resource_id);
    const a = accessByPair.get(`${m.source_resource_id}:${m.key}`);
    return {
      key: m.key,
      source_resource_id: m.source_resource_id,
      source_resource_name: r?.name ?? m.source_resource_id,
      source_kind: m.source_kind,
      sealed_blob: a?.sealed_blob ?? null,
      recipient_fingerprints: a?.recipient_fingerprints ?? [],
    };
  });

  // Pre-rendered placeholder-only `.env-mcp` template. Empty lines /
  // comments make it readable even when no resolution happens.
  const lines: string[] = ['# Generated by Cloud Resource Manager (mcp companion).', ''];
  // Group by source resource.
  const byResource = new Map<string, typeof envEntries>();
  for (const e of envEntries) {
    const arr = byResource.get(e.source_resource_id) ?? [];
    arr.push(e);
    byResource.set(e.source_resource_id, arr);
  }
  for (const [rid, group] of byResource) {
    const r = resByResource.get(rid);
    if (r) lines.push(`# Resource ${r.name} (${r.kind})`);
    for (const e of group) lines.push(`${e.key}=\${${e.key}}`);
    lines.push('');
  }

  return {
    mcp_json: composed.mcpJson,
    env_manifest: composed.envManifest,
    env_dotenv_template: lines.join('\n'),
    env_entries: envEntries,
  };
}

/**
 * cloud-resource-map.json — spec §6.7.1. Zero secrets, just metadata.
 * Idempotent (same DB state → same bytes hors `exported_at`).
 *
 * `usage` per access_key:
 *   - `session-injectable` ssi le Runner est recipient du blob
 *     correspondant (i.e. `runner_fp` figure dans
 *     `recipient_fingerprints`).
 *   - `browser-only` sinon.
 *
 * En Phase 7 il n'y a pas encore de Runner enregistré côté CRM —
 * `runner_fp` est laissé `null` et le projection retombe sur
 * `browser-only` pour toutes les clés (sécuritaire par défaut). Le
 * paramètre est exposé pour quand la Phase 8 ajoutera la pubkey du
 * Runner à la table `org_members` (cf. spec §4.2).
 */
export interface CloudResourceMapBody {
  readonly version: 1;
  readonly exported_at: string;
  readonly organization_id: string;
  readonly resources: ReadonlyArray<{
    readonly id: string;
    readonly scope: 'org' | 'project';
    readonly project_id: string | null;
    readonly variant: string | null;
    readonly kind: string;
    readonly name: string;
    readonly provider_metadata: Record<string, unknown>;
    readonly mcp_fragment: unknown;
    readonly egress_hosts: ReadonlyArray<string>;
    readonly access_keys: ReadonlyArray<{
      readonly key: string;
      readonly usage: 'session-injectable' | 'browser-only';
    }>;
    readonly secret_manager: { readonly kind: string; readonly name: string } | null;
  }>;
}

export interface CloudResourceMapInput {
  readonly organization_id: string;
  readonly exported_at: string;
  readonly resources: ReadonlyArray<ScopedResourceRow>;
  readonly accesses: ReadonlyArray<SealedAccessRow>;
  readonly secretManagers: ReadonlyMap<string, SecretManagerLookup>;
  readonly runnerFingerprint: string | null;
  readonly kindLookup: (kindId: string) =>
    | {
        mcpFragment?(metadata: unknown): unknown;
        egressHosts(metadata: unknown): ReadonlyArray<string>;
      }
    | undefined;
}

export function serializeCloudResourceMap(input: CloudResourceMapInput): CloudResourceMapBody {
  const accessesByResource = new Map<string, SealedAccessRow[]>();
  for (const a of input.accesses) {
    const arr = accessesByResource.get(a.resource_id) ?? [];
    arr.push(a);
    accessesByResource.set(a.resource_id, arr);
  }
  const runnerFp = input.runnerFingerprint?.toLowerCase() ?? null;

  const rows = input.resources
    .slice()
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .map((r) => {
      const kind = input.kindLookup(r.kind);
      let mcp_fragment: unknown = null;
      let egress: ReadonlyArray<string> = [];
      if (kind) {
        try {
          mcp_fragment =
            typeof kind.mcpFragment === 'function' ? kind.mcpFragment(r.provider_metadata) : null;
        } catch {
          mcp_fragment = null;
        }
        try {
          egress = kind.egressHosts(r.provider_metadata);
        } catch {
          egress = [];
        }
      }
      const accesses = accessesByResource.get(r.id) ?? [];
      const access_keys = accesses
        .slice()
        .sort((x, y) => (x.key < y.key ? -1 : x.key > y.key ? 1 : 0))
        .map((a) => {
          const sessionInjectable =
            runnerFp !== null && a.recipient_fingerprints.includes(runnerFp);
          return {
            key: a.key,
            usage: sessionInjectable ? ('session-injectable' as const) : ('browser-only' as const),
          };
        });
      const sm = input.secretManagers.get(r.secret_manager_id);
      return {
        id: r.id,
        scope: r.scope,
        project_id: r.project_id,
        variant: r.variant,
        kind: r.kind,
        name: r.name,
        provider_metadata: r.provider_metadata,
        mcp_fragment,
        egress_hosts: egress,
        access_keys,
        secret_manager: sm ? { kind: sm.kind, name: sm.name } : null,
      };
    });

  return {
    version: 1,
    exported_at: input.exported_at,
    organization_id: input.organization_id,
    resources: rows,
  };
}
