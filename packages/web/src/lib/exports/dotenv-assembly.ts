/**
 * Browser-side dotenv / json assembly for the Phase 7 exports.
 *
 * The CRM server returns `entries: [{ key, sealed_blob, ... }]`. This
 * helper unseals each blob with the live `identity`, assembles either
 * a `.env` text or a JSON object, and wipes the cleartext bytes
 * before returning.
 *
 * ZK invariant: every `Uint8Array` produced by `unsealAs` is `.fill(0)`
 * immediately after we read its UTF-8 content. The assembled text is
 * the final allowed copy, owned by the caller (passed to
 * `URL.createObjectURL`). For lines we cannot unseal, we substitute a
 * placeholder comment so the file still documents the missing slot.
 */

import { decodeUtf8, unsealAs, type SealedBlobV1 } from '@crm/core/crypto';

import type { Identity } from '@/lib/crypto/identity-store';

export interface AssemblableEntry {
  readonly key: string;
  readonly source_resource_id: string;
  readonly source_resource_name: string;
  readonly source_kind: string;
  readonly sealed_blob: SealedBlobV1 | null;
  readonly recipient_fingerprints: ReadonlyArray<string>;
}

export interface AssembleResult {
  /** UTF-8 string ready for Blob / download. */
  readonly text: string;
  /** Diagnostics: entries we successfully unsealed. */
  readonly resolved: ReadonlyArray<string>;
  /** Diagnostics: entries we could not unseal (user not a recipient). */
  readonly unavailable: ReadonlyArray<string>;
}

function isSealedBlobV1(value: unknown): value is SealedBlobV1 {
  if (typeof value !== 'object' || value === null) return false;
  const v = value as { v?: unknown; recipients?: unknown };
  return v.v === 1 && Array.isArray(v.recipients);
}

async function tryUnseal(
  entry: AssemblableEntry,
  identity: Identity,
): Promise<{ ok: true; value: string } | { ok: false; reason: 'no_blob' | 'not_recipient' }> {
  if (!entry.sealed_blob || !isSealedBlobV1(entry.sealed_blob)) {
    return { ok: false, reason: 'no_blob' };
  }
  const plain = await unsealAs(entry.sealed_blob, identity.fingerprint, {
    publicKey: identity.publicKey,
    privateKey: identity.privateKey,
  });
  if (plain === null) return { ok: false, reason: 'not_recipient' };
  const text = decodeUtf8(plain);
  plain.fill(0);
  return { ok: true, value: text };
}

/**
 * Assemble a `.env` text (dotenv format). One line per entry. Lines
 * are sorted by `key ASC` for deterministic byte output (testable).
 */
export async function assembleDotenv(
  entries: ReadonlyArray<AssemblableEntry>,
  identity: Identity,
  options: { readonly header?: string } = {},
): Promise<AssembleResult> {
  const header = options.header ?? '# Generated by Cloud Resource Manager.';
  const lines: string[] = [header, ''];
  const resolved: string[] = [];
  const unavailable: string[] = [];
  const sorted = entries.slice().sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  for (const entry of sorted) {
    const r = await tryUnseal(entry, identity);
    if (r.ok) {
      lines.push(`${entry.key}=${escapeDotenvValue(r.value)}`);
      resolved.push(entry.key);
    } else {
      const reason =
        r.reason === 'no_blob'
          ? 'no sealed_blob on the server'
          : 'request access from admin (re-seal needed)';
      lines.push(`# UNAVAILABLE: ${entry.key} (${reason})`);
      unavailable.push(entry.key);
    }
  }
  return { text: lines.join('\n'), resolved, unavailable };
}

/**
 * Assemble a JSON map `{ key: value }`. Same recipient gating as
 * `assembleDotenv`. Unresolved keys carry the literal placeholder
 * string `"UNAVAILABLE"` so the consumer can detect & retry.
 */
export async function assembleJson(
  entries: ReadonlyArray<AssemblableEntry>,
  identity: Identity,
): Promise<AssembleResult> {
  const out: Record<string, string> = {};
  const resolved: string[] = [];
  const unavailable: string[] = [];
  const sorted = entries.slice().sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  for (const entry of sorted) {
    const r = await tryUnseal(entry, identity);
    if (r.ok) {
      out[entry.key] = r.value;
      resolved.push(entry.key);
    } else {
      out[entry.key] = 'UNAVAILABLE';
      unavailable.push(entry.key);
    }
  }
  return { text: JSON.stringify(out, null, 2), resolved, unavailable };
}

/**
 * Assemble a `.env-mcp` companion file: same lines as `.env` but the
 * caller can pass a custom header (typically the mcp.json source
 * marker). Pure delegation to `assembleDotenv`.
 */
export async function assembleMcpCompanion(
  entries: ReadonlyArray<AssemblableEntry>,
  identity: Identity,
): Promise<AssembleResult> {
  return assembleDotenv(entries, identity, {
    header: '# Generated by Cloud Resource Manager (mcp companion).',
  });
}

/**
 * Escape a value for a POSIX-like `.env` line. We single-quote if the
 * value contains shell-sensitive characters (whitespace, `$`, `"`,
 * etc.) — single quotes preserve the literal in every common loader
 * (dotenv, direnv, sh).
 */
function escapeDotenvValue(value: string): string {
  if (value.length === 0) return '""';
  if (/^[A-Za-z0-9_.\-/:@+]+$/.test(value)) return value;
  return `'${value.replace(/'/g, `'\\''`)}'`;
}
