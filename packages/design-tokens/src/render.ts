/**
 * The two style sheets of the package, rendered from the palette
 * (`scripts/generate.ts` writes them; `tests/unit/sheets.test.ts` fails when
 * a committed sheet differs from its render):
 *
 * - `tokens.css` — the variable blocks alone, plain CSS: light on `:root`,
 *   `.light` and `[data-theme='light']`; dark on `.dark` and
 *   `[data-theme='dark']`, and on the system preference when no theme is
 *   chosen (`:root:not([data-theme]):not(.light)`, the app's "System" before
 *   first paint). The two dark blocks hold the same values.
 * - `theme.css` — what Tailwind v4 reads after `@import "tailwindcss"`: the
 *   `dark` variant on `.dark` or `[data-theme='dark']`, `@theme inline`
 *   (every colour as `--color-<name>`, the fonts, the type sizes, radii, the
 *   one shadow, motion), the base layer and the row utilities.
 */
import { cssOklch } from './color.ts';
import { SHADCN_TOKENS, VAUBAAN_TOKENS, TOKENS, type Token } from './palette.ts';

const GENERATED =
  'GENERATED by packages/design-tokens (npm run generate --workspace @vaubaan/design-tokens) from src/palette.ts: edit the palette there, never here.';

const SHADOW_OVERLAY = {
  light: '0 12px 32px oklch(0.21 0.015 250 / 0.14), 0 0 0 1px oklch(0.21 0.015 250 / 0.06)',
  dark: '0 16px 40px oklch(0 0 0 / 0.55), 0 0 0 1px oklch(1 0 0 / 0.08)',
};

type Theme = 'light' | 'dark';

function declarations(theme: Theme, indent: string): string {
  const lines: string[] = [];
  const groups: readonly [string, readonly Token[]][] = [
    ['shadcn', SHADCN_TOKENS],
    ['vaubaan', VAUBAAN_TOKENS],
  ];
  for (const [group, tokens] of groups) {
    lines.push(`${indent}/* — ${group} — */`);
    for (const token of tokens) {
      const hex = token[theme];
      const note = theme === 'light' && token.note ? ` · ${token.note}` : '';
      lines.push(`${indent}--${token.name}: ${cssOklch(hex)}; /* ${hex}${note} */`);
    }
  }
  lines.push(`${indent}--shadow-overlay: ${SHADOW_OVERLAY[theme]};`);
  return lines.join('\n');
}

export function renderTokensCss(): string {
  return `/*
 * Vaubaan design tokens — the "Trace" palette, shadcn/ui's variable names and Vaubaan's.
 * ${GENERATED}
 * Light = :root. Dark = .dark or [data-theme='dark'], or the system preference when no theme
 * is chosen. The two dark blocks are identical. The comment after each value is the sRGB hex
 * it was chosen as.
 */
:root,
.light,
[data-theme='light'] {
  color-scheme: light;
  --radius: 0.5rem; /* sm 4 · md 6 · lg 8 · xl 12 · 2xl 16 */
${declarations('light', '  ')}
}

.dark,
[data-theme='dark'] {
  color-scheme: dark;
${declarations('dark', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme]):not(.light) {
    color-scheme: dark;
${declarations('dark', '    ')}
  }
}
`;
}

export function renderThemeCss(): string {
  const colours = TOKENS.map((t) => `  --color-${t.name}: var(--${t.name});`).join('\n');
  return `/*
 * Vaubaan design tokens for Tailwind v4: import after "tailwindcss" and "./tokens.css".
 * ${GENERATED}
 */
@custom-variant dark (&:where(.dark, .dark *, [data-theme='dark'], [data-theme='dark'] *));

@theme inline {
${colours}

  /* Geist and Geist Mono, served by the app itself (the \`geist\` package through next/font). */
  --font-sans: var(--font-geist-sans), ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif;
  --font-mono: var(--font-geist-mono), ui-monospace, 'SF Mono', Menlo, Consolas, monospace;

  /* The app's four sizes; Tailwind's own scale (text-xs … text-6xl) stays for the site. The
     secondary lines are \`small\`: a size named \`secondary\` would share its utility with shadcn's
     \`secondary\` colour, and \`text-secondary\` resolves to the colour. */
  --text-caption: 0.75rem;
  --text-caption--line-height: 1rem;
  --text-small: 0.8125rem;
  --text-small--line-height: 1.25rem;
  --text-body: 0.875rem;
  --text-body--line-height: 1.375rem;
  --text-title: 1.25rem;
  --text-title--line-height: 1.75rem;
  --text-display: clamp(2.5rem, 4.2vw + 1rem, 4rem);
  --text-display--line-height: 1.05;

  /* shadcn's radius derivation. */
  --radius-sm: calc(var(--radius) - 4px);
  --radius-md: calc(var(--radius) - 2px);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) + 4px);
  --radius-2xl: calc(var(--radius) + 8px);

  /* One shadow, for what floats: shadcn's xs and sm (buttons, inputs) are flattened on purpose. */
  --shadow-2xs: 0 0 #0000;
  --shadow-xs: 0 0 #0000;
  --shadow-sm: 0 0 #0000;
  --shadow-md: var(--shadow-overlay);
  --shadow-lg: var(--shadow-overlay);
  --shadow-xl: var(--shadow-overlay);

  /* One atomic transition, 150 ms at most. */
  --ease-out: cubic-bezier(0.16, 1, 0.3, 1);
  --default-transition-duration: 150ms;
  --default-transition-timing-function: var(--ease-out);
}

@layer base {
  * {
    @apply border-border outline-ring/50;
  }
  html {
    -webkit-text-size-adjust: 100%;
  }
  body {
    @apply bg-background text-foreground font-sans antialiased;
  }
  :focus-visible {
    outline: 2px solid var(--ring);
    outline-offset: 2px;
  }
  /* An identifier wraps between its words, never inside one (style guide §5). */
  code,
  kbd,
  samp,
  .font-mono {
    font-variant-ligatures: none;
  }
  @media (prefers-reduced-motion: reduce) {
    *,
    *::before,
    *::after {
      animation-duration: 0ms !important;
      transition-duration: 0ms !important;
    }
  }
}

/* A row of the risk model as a light pill (style guide §5): its word carries the order. */
@utility row-1 {
  color: var(--row-1-fg);
  background: var(--row-1-bg);
  border-color: var(--row-1-border);
}
@utility row-2 {
  color: var(--row-2-fg);
  background: var(--row-2-bg);
  border-color: var(--row-2-border);
}
@utility row-3 {
  color: var(--row-3-fg);
  background: var(--row-3-bg);
  border-color: var(--row-3-border);
}
@utility row-4 {
  color: var(--row-4-fg);
  background: var(--row-4-bg);
  border-color: var(--row-4-border);
  font-weight: 600;
}
@utility tabular {
  font-variant-numeric: tabular-nums;
}
`;
}

/** The files of the package root and their content, as `scripts/generate.ts` writes them. */
export function renderedSheets(): Readonly<Record<'tokens.css' | 'theme.css', string>> {
  return { 'tokens.css': renderTokensCss(), 'theme.css': renderThemeCss() };
}
