#!/usr/bin/env node
// libsodium-wrappers-sumo@0.7.16 ships a broken ESM entry:
// `dist/modules-sumo-esm/libsodium-wrappers.mjs` imports
// `./libsodium-sumo.mjs` but that file is not in the published tarball.
// Webpack and Vitest sidestep it via package-name aliases to the CJS
// bundle (cf. next.config.ts / vitest.config.ts), but Playwright +
// Node ESM resolve the broken import directly and crash with
// `ERR_MODULE_NOT_FOUND`.
//
// We don't want to upgrade to 0.8.x because that family pulls in a
// separate `libsodium-sumo` package whose source uses `node:fs`
// imports webpack 5 can't bundle for the browser without extra
// fallback config — staying on 0.7.16 is the path of least churn.
//
// Fix: drop a sibling `libsodium-sumo.mjs` that re-exports from the
// `libsodium-sumo` peer (which we depend on explicitly at the same
// version). Node ESM resolves the relative import to this stub, the
// stub re-exports the real binary. Idempotent — running twice is a
// no-op once the file is in place.
//
// Triggered by the root `prepare` lifecycle (after `npm install`).
// In CI the `npm ci` step also runs `prepare`, so the patch is always
// applied before any test or build step.
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = dirname(here);

// npm workspaces hoist libsodium-wrappers-sumo wherever it sticks —
// sometimes the root node_modules, sometimes packages/<name>/node_modules.
// Walk every node_modules tree under the repo root and patch each
// occurrence. Cheap (each call does only one writeFileSync per missing
// target).
function findInstalls(root) {
  const out = [];
  const candidates = [join(root, 'node_modules', 'libsodium-wrappers-sumo')];
  const packagesDir = join(root, 'packages');
  if (existsSync(packagesDir)) {
    for (const entry of readdirSync(packagesDir)) {
      const name = String(entry);
      candidates.push(join(packagesDir, name, 'node_modules', 'libsodium-wrappers-sumo'));
    }
  }
  const buildWorktreesDir = join(root, '.build', 'worktrees');
  if (existsSync(buildWorktreesDir)) {
    for (const entry of readdirSync(buildWorktreesDir)) {
      const name = String(entry);
      candidates.push(join(buildWorktreesDir, name, 'node_modules', 'libsodium-wrappers-sumo'));
    }
  }
  for (const dir of candidates) {
    if (existsSync(dir) && statSync(dir).isDirectory()) {
      out.push(dir);
    }
  }
  return out;
}

const stub = `// Auto-generated by scripts/patch-libsodium-esm.mjs.
// Bridges the broken ESM entry of libsodium-wrappers-sumo@0.7.16.
export { default } from 'libsodium-sumo';
`;

let patched = 0;
for (const pkgDir of findInstalls(repoRoot)) {
  const target = join(pkgDir, 'dist', 'modules-sumo-esm', 'libsodium-sumo.mjs');
  if (existsSync(target)) continue;
  writeFileSync(target, stub, 'utf8');
  patched++;
}
if (patched > 0) {
  console.log(`patch-libsodium-esm: stubbed ${patched} libsodium-sumo.mjs`);
}
